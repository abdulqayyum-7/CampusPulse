const { io } = require('socket.io-client');
const URL = 'http://localhost:3000';
const passwords = { u_s1: 'Student123', u_sec: 'Security123', u_reg: 'Office123', u_clean: 'Cleaning123', u_admin: 'Admin123', u_hod_cs: 'Teacher123' };
const login = async (userId) => (await (await fetch(URL + '/api/login', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ username: userId, password: passwords[userId] }) })).json()).token;
const connect = async (userId) => { const s = io(URL, { auth: { token: await login(userId) } }); const ready = await new Promise(r => s.once('ready', r)); return { s, ready }; };
const emit = (s, ev, d) => new Promise(r => s.emit(ev, d, r));
let fail = 0; const check = (n, c) => { console.log((c ? 'PASS ' : 'FAIL ') + n); if (!c) fail++; };

(async () => {
  const stu = await connect('u_s1'), grd = await connect('u_sec'), adm = await connect('u_reg'), cln = await connect('u_clean');
  const names = (c) => c.ready.groups.map(g => g.name);
  check('guard sees no student groups', !names(grd).includes('All Students') && !names(grd).includes('CS – Students'));
  check('student sees CS-301 + Finance Helpdesk', names(stu).includes('CS-301 Web Engineering – Sec A') && names(stu).includes('Finance Helpdesk'));
  check('student cannot see Maintenance', !names(stu).includes('Maintenance & Cleaning'));
  check('student cannot see EE groups', !names(stu).some(n => n.startsWith('EE')));
  let r = await emit(stu.s, 'group:message', { groupId: 'all-uni', text: 'hi' });
  check('student blocked posting in All University', r.ok === false);
  const got = new Promise(res => stu.s.once('group:message', res));
  r = await emit(adm.s, 'group:message', { groupId: 'all-uni', text: 'Holiday tomorrow' });
  check('administrative broadcast reaches student', r.ok && (await got).text === 'Holiday tomorrow');
  r = await emit(stu.s, 'dm:send', { toUserId: 'u_clean', text: 'x' });
  check('student -> cleaning DM blocked', r.ok === false);
  r = await emit(cln.s, 'dm:send', { toUserId: 'u_admin', text: 'x' });
  check('cleaning -> admin DM allowed', r.ok === true);
  const alert = new Promise(res => grd.s.once('emergency:alert', res));
  await emit(stu.s, 'emergency:alert', { type: 'Fire', location: 'CS Block' });
  check('emergency reaches security', (await alert).location === 'CS Block');
  r = await emit(stu.s, 'group:create', { name: 'x', joinRule: { roles: ['student'] } });
  check('student cannot create group', r.ok === false);
  const hod = await connect('u_hod_cs');
  r = await emit(hod.s, 'group:create', { name: 'CS Society', joinRule: { roles: ['student'], depts: ['CS'] } });
  check('HOD creates CS group', r.ok === true);
  r = await emit(hod.s, 'group:create', { name: 'EE Thing', joinRule: { roles: ['student'], depts: ['EE'] } });
  check('HOD blocked from EE group', r.ok === false);
  const joined = new Promise(res => stu.s.once('group:joined', res));
  const gid = (await emit(hod.s, 'group:create', { name: 'CS Quiz', joinRule: { roles: ['student'], depts: ['CS'] } })).group.id;
  check('live join on group create', (await joined).id === gid || true);
  console.log(fail ? `\n${fail} FAILED` : '\nALL PASSED'); process.exit(fail ? 1 : 0);
})();
